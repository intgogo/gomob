package laser

// cartype.go = 车型 carType 三轴偏移表（Go 镜像，逆向自原厂 JCHY，docs/architecture/16 §4.3）。
// 原厂语义：选定车型后把该型 (x,y,z) 偏移(mm)叠加到测量 ROI/区域中心，补偿不同车型车体相对扫描
// 区域的位置差。与 native/measurement/vehicle_catalog（读 carType.ini 解密）同源；此处 Go 侧嵌入已
// 逐字节复算一致的解码值（measure.go 不引 cgo，按 pcd.go 镜像范式）。
//
// 注：tank/board/Type2_s 等子变体(Tank5/Tank7/Tank15…)按车体细分形态触发，需运行时分类，暂未接；
// 这里用每车型基础 Type<n> 偏移。逐型限值/子变体见 docs/16 §4.3，待 M9.2b 补。

// 车型编号 → 偏移(mm)。未列编号（及 -1=未选）偏移为 0。
var carTypeOffsets = map[int][3]float32{
	0:  {-20, -35, 0},  // 牵引头
	1:  {-60, -35, 0},  // 吊车
	2:  {-20, -35, -10}, // 常规
	3:  {20, -45, 0},   // 路边清障车
	4:  {-40, -10, 0},  // 垃圾清理车
	5:  {-20, -45, 0},  // 洒水罐车
	6:  {-50, -45, 0},  // 小型平板货车
	7:  {20, 5, 0},     // 水泥搅拌车
	8:  {40, -45, 0},   // 大型平板货车
	9:  {-40, -15, 0},  // 特殊吊车
	10: {-40, -25, 0},  // 特殊栏板吊车
	11: {-40, -40, 0},  // 专项特殊车
	12: {-30, -35, 0},  // 箱式尾板车
	13: {0, 0, 0},      // 自卸式货车
	14: {0, 0, 0},      // 仓栅式货车
	15: {0, 0, 0},      // 箱式货车
	50: {-50, -20, 0},  // 常规挂车
	51: {90, -100, 10}, // 光板挂车
	52: {-50, -20, 0},  // 光板挂车（带杆）
	53: {-20, -10, 0},  // 常规罐体挂车
	54: {30, 0, 0},     // 低平板挂车
	55: {70, 0, 0},     // 异型挂车
	56: {0, 0, 0},      // 箱式挂车
	57: {0, 0, 0},      // 仓栅式挂车
	58: {-50, -10, 0},  // 下灰式罐体挂车
	59: {50, -10, 0},   // 水泥罐体挂车
}

// CarTypeOffset 返回车型编号的三轴偏移(mm)；未选(-1)/未知编号返回零偏移。
func CarTypeOffset(vehicleTypeID int) [3]float32 {
	if o, ok := carTypeOffsets[vehicleTypeID]; ok {
		return o
	}
	return [3]float32{0, 0, 0}
}
